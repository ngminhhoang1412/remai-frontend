#!/usr/bin/env node
// Writes dist/_headers for Cloudflare Pages (design D7 of adopt-flutter-and-serverless).
// Runs after `vite build` (see the `build` script in package.json).
//
// The CSP's connect-src is generated from VITE_API_URL so that the API origin is configured
// in exactly one place. VITE_API_URL is resolved the same way Vite resolves it for the bundle
// (.env, .env.local, .env.[mode], .env.[mode].local, then the process environment), so the
// header and the bundled client can never disagree.
//
// Behaviour:
// - VITE_API_URL missing or empty: falls back to http://localhost:8080, like src/config.ts,
//   and prints a warning.
// - VITE_API_URL malformed (not an absolute http(s) URL, or carrying credentials): the script
//   exits with status 1, which fails `npm run build`.
// - dist/404.html exists: exits with status 1 (see assertSpaFallback).

import { existsSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Must match DEFAULT_API_URL in src/config.ts. */
export const DEFAULT_API_URL = 'http://localhost:8080'

/**
 * Returns the origin (scheme://host[:port]) of an API base URL.
 * Throws on anything that isn't an absolute http(s) URL without credentials.
 * @param {string | undefined} raw
 * @returns {{ origin: string, usedDefault: boolean }}
 */
export function resolveApiOrigin(raw) {
  const value = (raw ?? '').trim()
  if (value === '') {
    return { origin: new URL(DEFAULT_API_URL).origin, usedDefault: true }
  }
  let url
  try {
    url = new URL(value)
  } catch {
    throw new Error(`VITE_API_URL is not a valid absolute URL: ${JSON.stringify(value)}`)
  }
  if (url.protocol !== 'https:' && url.protocol !== 'http:') {
    throw new Error(`VITE_API_URL must use http or https, got ${JSON.stringify(url.protocol)}`)
  }
  if (url.username !== '' || url.password !== '') {
    throw new Error('VITE_API_URL must not contain credentials')
  }
  // URL#origin is normalised (lower-case host, default port dropped) and can't contain
  // spaces, ';' or ',', so it can't inject extra CSP directives or header values.
  return { origin: url.origin, usedDefault: false }
}

/**
 * Builds the Content-Security-Policy value.
 * Scripts and styles come only from the web origin. React's `style={...}` props are applied
 * through the CSSOM (element.style), which CSP doesn't restrict, so no 'unsafe-inline' is needed.
 * @param {string} apiOrigin
 */
export function buildCsp(apiOrigin) {
  return [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self'",
    "img-src 'self'",
    "font-src 'self'",
    `connect-src 'self' ${apiOrigin}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ')
}

/**
 * Renders the Cloudflare Pages `_headers` file.
 * Pages joins values when several rules set the same header, so `/assets/*` detaches the
 * HTML rule's Cache-Control (`! Cache-Control`) before setting its own.
 * `/*` also covers `/` and every deep link rewritten to index.html by `_redirects`.
 * @param {string} apiOrigin
 */
export function buildHeadersFile(apiOrigin) {
  return [
    '# Generated by scripts/write-headers.mjs during `npm run build`. Do not edit.',
    '/*',
    `  Content-Security-Policy: ${buildCsp(apiOrigin)}`,
    '  X-Content-Type-Options: nosniff',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    '  Cache-Control: no-cache',
    '',
    '/assets/*',
    '  ! Cache-Control',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
  ].join('\n')
}

/**
 * Deep links (`/p/<id>`, `/trash`, ...) rely on Cloudflare Pages' built-in SPA fallback: when the
 * output has no top-level 404.html, any path that isn't a static asset is answered with
 * index.html and status 200. A `_redirects` rule can't do this: Pages ignores
 * `/* /index.html 200` as an infinite loop, and `/* / 200` would also shadow /assets/*.
 * Adding a 404.html would silently turn deep links into 404s, so the build refuses it.
 * @param {string} distDir
 * @param {(path: string) => boolean} [exists]
 */
export function assertSpaFallback(distDir, exists = existsSync) {
  if (exists(resolve(distDir, '404.html'))) {
    throw new Error(
      'dist/404.html would disable the Cloudflare Pages SPA fallback and break deep links; remove it',
    )
  }
}

function parseMode(argv) {
  const i = argv.indexOf('--mode')
  return i >= 0 && argv[i + 1] ? argv[i + 1] : 'production'
}

async function main() {
  const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
  const mode = parseMode(process.argv.slice(2))
  const { loadEnv } = await import('vite')
  const env = loadEnv(mode, root, 'VITE_')
  const { origin, usedDefault } = resolveApiOrigin(env.VITE_API_URL)
  if (usedDefault) {
    console.warn(`write-headers: VITE_API_URL is not set; CSP connect-src uses ${origin}`)
  }
  const dist = resolve(root, 'dist')
  assertSpaFallback(dist)
  const out = resolve(dist, '_headers')
  writeFileSync(out, buildHeadersFile(origin))
  console.log(`write-headers: wrote dist/_headers (connect-src 'self' ${origin})`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    await main()
  } catch (err) {
    console.error(`write-headers: ${err instanceof Error ? err.message : String(err)}`)
    process.exit(1)
  }
}
